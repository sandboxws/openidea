/**
 * Generates the Gruvppuccin plugin (`plugins/gruvppuccin/`) from its vendored palette data:
 *
 *   node scripts/gruvppuccin/generate.ts           # write plugin.toml, themes/, icons/theme.json
 *   node scripts/gruvppuccin/generate.ts --check   # fail if any of them is stale
 *
 * 21 palettes × Classic / Island / Soft Island = 63 themes, each with the palette's editor
 * scheme, plus the file icon theme. Token values come from `roles.ts`; the token list comes
 * from `src/styles/tokens.css` (via `scripts/theme/tokens.ts`), so a token upstream adds fails
 * `generate.test.ts` until `roles.ts` gives it a role.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { themeTokenGroups, type TokenGroup } from "../theme/tokens.ts";
import type { PaletteData } from "./extract.ts";
import { STYLES, type Style } from "./model.ts";
import { SCHEME_ROLES, UI_ROLES, context, paletteTokens, schemeExtras, styleTokens, type Ctx } from "./roles.ts";

export const PLUGIN_ID = "gruvppuccin";

/** Picker order: the original trio, then the Embark blends, Gruvbark, and the Nocturne palettes. */
const FAMILY_ORDER = ["gruvppuccin", "embark", "gruvbark", "nocturne"] as const;
const TRIO = ["macchiato", "mocha", "latte"];

export function orderPalettes(palettes: readonly PaletteData[]): PaletteData[] {
  const rank = (p: PaletteData) => {
    const family = FAMILY_ORDER.indexOf(p.family);
    const trio = TRIO.indexOf(p.id);
    return family * 100 + (trio >= 0 ? trio : 10);
  };
  return [...palettes].sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
}

export function themeId(p: PaletteData, style: Style): string {
  return style === "classic" ? p.id : `${p.id}-${style}`;
}

export function themeName(p: PaletteData, style: Style): string {
  return style === "classic" ? p.name : `${p.name} ${style === "island" ? "Island" : "Soft Island"}`;
}

function title(group: string): string {
  return group.charAt(0).toUpperCase() + group.slice(1);
}

interface Section {
  title: string;
  tokens: Record<string, string>;
}

function sections(groups: readonly TokenGroup[], scheme: boolean, c: Ctx): Section[] {
  const roles = scheme ? SCHEME_ROLES : UI_ROLES;
  return groups
    .filter((g) => g.scheme === scheme)
    .map((g) => ({
      title: title(g.title),
      tokens: Object.fromEntries(
        g.tokens.map((t) => {
          const role = roles[t.name];
          if (!role) throw new Error(`${scheme ? "scheme" : "UI"} token ${t.name} has no role in roles.ts`);
          return [t.name, role(c)];
        }),
      ),
    }));
}

/** JSONC in the shape oxfmt leaves alone: one key per line, a comment before each section. */
function jsonc(header: string[], head: Record<string, string>, body: Section[]): string {
  const lines = header.map((l) => `// ${l}`);
  lines.push("{");
  for (const [k, v] of Object.entries(head)) lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  lines.push('  "tokens": {');
  const nonEmpty = body.filter((s) => Object.keys(s.tokens).length > 0);
  nonEmpty.forEach((s, i) => {
    if (i > 0) lines.push("");
    lines.push(`    // ${s.title}`);
    const entries = Object.entries(s.tokens);
    entries.forEach(([k, v], j) => {
      const last = i === nonEmpty.length - 1 && j === entries.length - 1;
      lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(v)}${last ? "" : ","}`);
    });
  });
  lines.push("  }");
  lines.push("}");
  return lines.join("\n") + "\n";
}

export function themeFile(p: PaletteData, style: Style, groups: readonly TokenGroup[]): string {
  const c = context(p, style);
  return jsonc(
    [
      `${themeName(p, style)}: UI theme, generated by scripts/gruvppuccin/generate.ts`,
      "from data/palettes.json. Edit roles.ts (or re-extract the palettes) instead of this file.",
    ],
    { id: themeId(p, style), name: themeName(p, style), kind: p.kind },
    [
      ...sections(groups, false, c),
      { title: "Gruvppuccin palette and accent slots", tokens: paletteTokens(p) },
      { title: "Classic style: hairline borders instead of islands", tokens: styleTokens(c) },
    ],
  );
}

/** Scheme roles outside upstream's token reference (Gruvppuccin's keyword roles). */
function extraSchemeTokens(groups: readonly TokenGroup[], c: Ctx): Record<string, string> {
  const known = new Set(groups.flatMap((g) => g.tokens.map((t) => t.name)));
  return Object.fromEntries(
    Object.entries(SCHEME_ROLES)
      .filter(([name]) => !known.has(name))
      .map(([name, role]) => [name, role(c)]),
  );
}

export function schemeFile(p: PaletteData, groups: readonly TokenGroup[]): string {
  const c = context(p, "classic");
  return jsonc(
    [
      `${p.name}: editor colour scheme (shared by its Classic, Island and Soft Island themes),`,
      "generated by scripts/gruvppuccin/generate.ts from data/palettes.json.",
    ],
    { name: p.name },
    [
      ...sections(groups, true, c),
      { title: "Keyword roles (import, return, control flow, declarations)", tokens: extraSchemeTokens(groups, c) },
      { title: "Editor surfaces and font styles", tokens: schemeExtras(c) },
    ],
  );
}

/** The file icon theme: IntelliJ's GruvppuccinIconProvider mapping, light and dark SVGs. */
export const ICON_EXTENSIONS: Record<string, string[]> = {
  kotlin: ["kt", "kts"],
  java: ["java"],
  go: ["go"],
  swift: ["swift"],
  javascript: ["js", "mjs", "cjs"],
  typescript: ["ts", "mts", "cts"],
  jsx: ["jsx"],
  tsx: ["tsx"],
  python: ["py"],
  ruby: ["rb"],
  php: ["php"],
  html: ["html", "htm"],
  css: ["css"],
  scss: ["scss"],
  json: ["json"],
  yaml: ["yaml", "yml"],
  markdown: ["md"],
  shell: ["sh", "bash", "zsh"],
  xml: ["xml"],
  rust: ["rs"],
  c: ["c", "h"],
  cpp: ["cpp", "hpp", "cc"],
  git: ["gitignore", "gitattributes"],
};
export const ICON_FILE_NAMES: Record<string, string> = {
  dockerfile: "docker",
  ".gitignore": "git",
  ".gitattributes": "git",
};
/** Built-in IDE icons the theme's `icons` block replaced in IntelliJ → their SVG (`icons/<variant>/<svg>.svg`). */
export const ICON_OVERRIDES: Record<string, string> = {
  module: "module",
  "folder-source": "sourceRoot",
  info: "info",
  "gradle-project": "gradle",
  "build-task": "task",
  "build-task-group": "taskGroup",
};

/** Icon ids are lowercase (`sourceRoot.svg` → `source-root`). */
export function iconId(svg: string): string {
  return svg.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

export function iconTheme(): string {
  const svgs = [
    ...new Set([...Object.keys(ICON_EXTENSIONS), ...Object.values(ICON_FILE_NAMES), ...Object.values(ICON_OVERRIDES)]),
  ].sort();
  const theme = {
    iconDefinitions: Object.fromEntries(
      svgs.map((svg) => [iconId(svg), { light: `icons/light/${svg}.svg`, dark: `icons/dark/${svg}.svg` }]),
    ),
    fileExtensions: Object.fromEntries(
      Object.entries(ICON_EXTENSIONS).flatMap(([icon, exts]) => exts.map((ext) => [ext, icon])),
    ),
    fileNames: ICON_FILE_NAMES,
    overrides: Object.fromEntries(Object.entries(ICON_OVERRIDES).map(([name, svg]) => [name, iconId(svg)])),
    settings: [
      {
        title: "Icons",
        items: [
          { option: "hideFiles", invert: true, label: "Show file icons" },
          {
            option: "hideUiIcons",
            invert: true,
            label: "Replace IDE icons",
            hint: "Module, source root, Gradle and task icons",
          },
        ],
      },
    ],
  };
  return JSON.stringify(theme, null, 2) + "\n";
}

function tomlString(s: string): string {
  return JSON.stringify(s);
}

export function manifest(palettes: readonly PaletteData[]): string {
  const lines = [
    "# Generated by scripts/gruvppuccin/generate.ts; edit that script instead.",
    "# Data only: 63 themes (21 palettes × Classic / Island / Soft Island) and a file icon theme.",
    "# The accent, preset and corner-radius settings live in the fork's Gruvppuccin feature.",
    `id = ${tomlString(PLUGIN_ID)}`,
    'name = "Gruvppuccin"',
    'version = "1.0.0"',
    'description = "Gruvbox × Catppuccin, Embark and Nocturne blends: 63 warm, earthy themes in Classic, Island and Soft Island styles, with a matching file icon theme."',
    'authors = ["Ahmed Elhossaini"]',
    'license = "LicenseRef-Proprietary"',
    'categories = ["themes", "icon-themes"]',
    'change-notes = "1.0.0 — ported from the Gruvppuccin IntelliJ theme."',
    'engines.openidea = "^1.0"',
  ];
  for (const p of orderPalettes(palettes)) {
    for (const style of STYLES) {
      lines.push("", "[[contributes.themes]]");
      lines.push(`path = ${tomlString(`themes/${themeId(p, style)}.theme.json`)}`);
      lines.push(`editor-scheme = ${tomlString(`themes/${p.id}.scheme.json`)}`);
    }
  }
  lines.push(
    "",
    "[[contributes.iconThemes]]",
    'id = "gruvppuccin"',
    'label = "Gruvppuccin Icons"',
    'path = "icons/theme.json"',
  );
  return lines.join("\n") + "\n";
}

/** Every generated file, relative to the plugin directory. */
export function buildPackage(palettes: readonly PaletteData[], tokensCss: string): Map<string, string> {
  const groups = themeTokenGroups(tokensCss);
  const files = new Map<string, string>();
  files.set("plugin.toml", manifest(palettes));
  for (const p of palettes) {
    files.set(`themes/${p.id}.scheme.json`, schemeFile(p, groups));
    for (const style of STYLES) files.set(`themes/${themeId(p, style)}.theme.json`, themeFile(p, style, groups));
  }
  files.set("icons/theme.json", iconTheme());
  return files;
}

/** The fork's Gruvppuccin runtime (`src/features/gruvppuccin`) needs each palette's accent labels. */
export const RUNTIME_DATA = "src/features/gruvppuccin/palettes.generated.json";

export function runtimeData(palettes: readonly PaletteData[]): string {
  const labels: Record<string, Record<string, string>> = {};
  for (const p of orderPalettes(palettes)) {
    const own = Object.entries(p.labels).filter(([slot, label]) => label.toLowerCase() !== slot);
    if (own.length) labels[p.id] = Object.fromEntries(own);
  }
  return JSON.stringify({ labels }, null, 2) + "\n";
}

export const PLUGIN_DIR = fileURLToPath(new URL("../../plugins/gruvppuccin/", import.meta.url));
export const REPO_DIR = fileURLToPath(new URL("../../", import.meta.url));
const TOKENS_CSS = fileURLToPath(new URL("../../src/styles/tokens.css", import.meta.url));

export function loadPalettes(): PaletteData[] {
  return (JSON.parse(readFileSync(join(PLUGIN_DIR, "data/palettes.json"), "utf8")) as { palettes: PaletteData[] })
    .palettes;
}

function main(): void {
  const check = process.argv.includes("--check");
  const palettes = loadPalettes();
  const files = new Map<string, string>();
  for (const [rel, content] of buildPackage(palettes, readFileSync(TOKENS_CSS, "utf8")))
    files.set(join(PLUGIN_DIR, rel), content);
  files.set(join(REPO_DIR, RUNTIME_DATA), runtimeData(palettes));
  const stale: string[] = [];
  for (const [path, content] of files) {
    const rel = path.startsWith(REPO_DIR) ? path.slice(REPO_DIR.length) : path;
    let current: string | null = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) stale.push(rel);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  if (check && stale.length) {
    console.error(`stale (run node scripts/gruvppuccin/generate.ts):\n  ${stale.join("\n  ")}`);
    process.exitCode = 1;
  } else console.log(check ? `${files.size} files up to date` : `wrote ${files.size} files`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
